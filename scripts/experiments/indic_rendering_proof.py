CASE_ORDER = ["word", "sentence", "paragraph", "punctuation", "numerals", "mixed"]

# Rect height budget per case (points). Paragraph gets more room; the
# rest get a deliberately tight box so overflow/clipping is observable.
CASE_HEIGHT = {
    "word": 40,
    "sentence": 40,
    "paragraph": 90,
    "punctuation": 40,
    "numerals": 40,
    "mixed": 55,
}

PAGE_WIDTH, PAGE_HEIGHT = 595.28, 841.89  # A4
BOX_X0, BOX_X1 = 40, PAGE_WIDTH - 40
BOX_FONT_SIZE = 16


@dataclass
class CaseResult:
    language: str
    case: str
    input_text: str
    rect: tuple
    html: str
    css: str
    spare_height: float
    scale: float
    clipped: bool
    error: str | None = None
    png_path: str | None = None


def render_language(lang_key: str, spec: dict) -> list[CaseResult]:
    font_path = FONTS_DIR / lang_key / spec["font_file"]
    if not font_path.exists():
        raise FileNotFoundError(f"Missing font file: {font_path}")

    archive = pymupdf.Archive(str(font_path.parent))
    css = (
        f"@font-face {{font-family: {spec['font_family']}; "
        f"src: url({spec['font_file']});}}\n"
        f"* {{font-family: {spec['font_family']}; "
        f"font-size: {BOX_FONT_SIZE}px;}}"
    )

    doc = pymupdf.open()
    page = doc.new_page(width=PAGE_WIDTH, height=PAGE_HEIGHT)

    results: list[CaseResult] = []
    y = 30.0
    label_font = pymupdf.Font("helv")

    for case in CASE_ORDER:
        text = spec["cases"][case]
        height = CASE_HEIGHT[case]

        # Label (plain Latin, no shaping needed) above the test box.
        page.insert_text(
            (BOX_X0, y + 10),
            f"[{spec['label']} / {case}]",
            fontsize=9,
            fontname="helv",
            color=(0.4, 0.4, 0.4),
        )
        rect = pymupdf.Rect(BOX_X0, y + 14, BOX_X1, y + 14 + height)
        # Draw the rect border so clipping is visible in the render.
        page.draw_rect(rect, color=(0.7, 0.7, 0.7), width=0.5)

        html = f"<p>{text}</p>"
        error = None
        try:
            spare_height, scale = page.insert_htmlbox(
                rect, html, css=css, archive=archive, scale_low=1.0
            )
        except Exception as exc:  # noqa: BLE001 - record any failure verbatim
            spare_height, scale = -1.0, 0.0
            error = repr(exc)

        clipped = spare_height == -1.0
        results.append(
            CaseResult(
                language=lang_key,
                case=case,
                input_text=text,
                rect=(rect.x0, rect.y0, rect.x1, rect.y1),
                html=html,
                css=css,
                spare_height=spare_height,
                scale=scale,
                clipped=clipped,
                error=error,
            )
        )

        y += 14 + height + 16

    # Render full page (all cases for this language) at 2x for inspection.
    pix = page.get_pixmap(matrix=pymupdf.Matrix(2, 2))
    full_png = OUT_DIR / f"{lang_key}_all_cases.png"
    pix.save(str(full_png))

    # Also save an individual crop per case for the report table.
    for i, case in enumerate(CASE_ORDER):
        r = results[i]
        rect = pymupdf.Rect(*r.rect)
        crop = pymupdf.Rect(rect.x0 - 5, rect.y0 - 20, rect.x1, rect.y1 + 5)
        pix_crop = page.get_pixmap(matrix=pymupdf.Matrix(3, 3), clip=crop)
        crop_path = OUT_DIR / f"{lang_key}_{case}.png"
        pix_crop.save(str(crop_path))
        r.png_path = str(crop_path.relative_to(ROOT)).replace("\\", "/")

    pdf_path = OUT_DIR / f"{lang_key}_proof.pdf"
    doc.save(str(pdf_path))
    doc.close()

    return results


def main() -> None:
    all_results: list[CaseResult] = []
    for lang_key, spec in LANGUAGES.items():
        print(f"Rendering {spec['label']}...")
        all_results.extend(render_language(lang_key, spec))

    # Dump machine-readable results for the report-writing step.
    out_json = OUT_DIR / "results.json"
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(
            [
                {
                    "language": r.language,
                    "case": r.case,
                    "input_text": r.input_text,
                    "rect": r.rect,
                    "spare_height": r.spare_height,
                    "scale": r.scale,
                    "clipped": r.clipped,
                    "error": r.error,
                    "png_path": r.png_path,
                }
                for r in all_results
            ],
            f,
            ensure_ascii=False,
            indent=2,
        )
    print(f"\nWrote {len(all_results)} results to {out_json}")
    print(f"PyMuPDF version: {PYMUPDF_VERSION}")

    # Quick console summary.
    for r in all_results:
        status = "CLIPPED" if r.clipped else f"ok (spare={r.spare_height:.1f}, scale={r.scale:.2f})"
        err = f" ERROR={r.error}" if r.error else ""
        print(f"  {r.language:12s} {r.case:12s} {status}{err}")


if __name__ == "__main__":
    main()
